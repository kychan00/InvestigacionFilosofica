import {readFile,mkdir,writeFile} from "node:fs/promises";
import {join} from "node:path";
import {createHash} from "node:crypto";
const [snapshotRoot,docRoot,scopedRoot,out]=process.argv.slice(2);
if(!out)throw Error("Usage: build-review-workbench-v2.mjs SNAPSHOT DOCUMENTARY SCOPED OUTPUT");
const sha=b=>createHash("sha256").update(b).digest("hex");
const read=async p=>JSON.parse(await readFile(p,"utf8"));
const rows=b=>b.toString("utf8").trim().split(/\r?\n/).filter(Boolean).map(JSON.parse);
const snapshot=await read(join(snapshotRoot,"snapshot-shadow.json"));
const rev=snapshot.datasetRevision;
const sample=await readFile(join(snapshotRoot,"review-sample.jsonl"));
const evidence=await read(join(snapshotRoot,"review-evidence.json"));
if(snapshot.schemaVersion!=="authority-snapshot-shadow-v2"||!rev||sha(sample)!==snapshot.provenance?.sampleSha256||evidence.sampleSha256!==sha(sample))throw Error("Pilot sample binding mismatch");
const byId=new Map(evidence.cases.map(c=>[c.audit_id,c]));
const pilot=rows(sample).map(c=>{
 const e=byId.get(c.audit_id);
 if(!e||String(e.left.authorId)!==String(c.left.authorId)||String(e.right.authorId)!==String(c.right.authorId))throw Error("Pilot profile binding mismatch");
 return {audit_id:c.audit_id,task:"identity-pair",cohort:"pilot",profiles:[e.left,e.right],judgment:null};
});
const sources={pilot:{sampleSha256:sha(sample),cases:pilot.length}};
const cases=[...pilot];
const doc=await read(join(docRoot,"manifest.json"));
const docRaw=await readFile(join(docRoot,"review-cases.jsonl"));
if(doc.schemaVersion!=="authority-v2-documentary-review-v1"||doc.datasetRevision!==rev||doc.reviewSha256!==sha(docRaw))throw Error("Documentary sample binding mismatch");
sources.documentary={sampleSha256:sha(docRaw),cases:doc.totalCases};
cases.push(...rows(docRaw).map(({stratum,...c})=>({...c,cohort:"documentary"})));
const scoped=await read(join(scopedRoot,"manifest.json"));
if(scoped.schemaVersion!=="authority-v2-scoped-review-v1"||scoped.datasetRevision!==rev||scoped.documentaryReviewSha256!==doc.reviewSha256)throw Error("Scoped review binding mismatch");
for(const name of ["contribution","portrait"]){
 const dir=join(scopedRoot,name),manifest=await read(join(dir,"manifest.json")),raw=await readFile(join(dir,"cases.jsonl"));
 const list=rows(raw);
 if(manifest.schemaVersion!=="authority-v2-scope-packet-v1"||manifest.scope!==name||manifest.datasetRevision!==rev||manifest.sampleSha256!==sha(raw)||manifest.cases!==list.length)throw Error("Scoped sample binding mismatch");
 sources[name]={sampleSha256:sha(raw),cases:list.length};
 cases.push(...list.map(c=>({...c,cohort:name})));
}
if(pilot.length!==100||sources.documentary.cases!==300||cases.length!==Object.values(sources).reduce((n,s)=>n+s.cases,0)||new Set(cases.map(c=>c.audit_id)).size!==cases.length||cases.some(c=>c.judgment!==null))throw Error("Invalid or duplicate review cases");
const data={schemaVersion:"authority-v2-workbench-packet-v1",datasetRevision:rev,sources,cases};
const packetSha256=sha(JSON.stringify(data));
const packet={...data,packetSha256};
const template=await readFile(new URL("../../benchmark/author-authority/v2/review-workbench.html",import.meta.url),"utf8");
const core=await readFile(new URL("../../src/core/author-authority-review-workbench-v2.js",import.meta.url),"utf8");
const app=await readFile(new URL("./review-workbench-v2-browser.js",import.meta.url),"utf8");
if(/<\/script/i.test(core+"\n"+app))throw Error("Unsafe inline script source");
const safeJson=JSON.stringify(packet).replace(/</g,"\\u003c").replace(/\u2028/g,"\\u2028").replace(/\u2029/g,"\\u2029");
const html=template.replace("<!-- PACKET -->",()=>'<script type="application/json" id="packet-data">'+safeJson+'</script>').replace("<!-- APPLICATION -->",()=>'<script type="module">'+core+"\n"+app+'</script>');
await mkdir(out,{recursive:true});
await writeFile(join(out,"review.html"),html);
await writeFile(join(out,"packet.json"),JSON.stringify(packet,null,2)+"\n");
await writeFile(join(out,"README.txt"),"Abra review.html en un navegador local. No requiere servidor ni conexión para leer los expedientes. Consulte fuentes mediante los enlaces. Guarde cada juicio y exporte el progreso antes de cerrar. Reimporte el JSON para continuar. Exportar piloto genera el formato del analizador existente; las demás métricas requieren un análisis posterior. No se incluyen predicciones ni asignaciones de método. No es una aprobación científica.\n");
console.log("AUTHORITY_V2_REVIEW_WORKBENCH "+JSON.stringify({packetSha256,datasetRevision:rev,cases:cases.length,byCohort:sources,reviewed:0,htmlBytes:Buffer.byteLength(html)}));
