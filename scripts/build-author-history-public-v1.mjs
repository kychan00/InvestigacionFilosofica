import {readFileSync,writeFileSync} from "node:fs";
import {resolve} from "node:path";
import {pathToFileURL} from "node:url";

export function renderPublicHistory(ledger){
 const urls=[],indices=new Map(),entries={};
 for(const r of ledger.entries){
  if(r.publicationReview?.status==="correction-required")throw Error("Unresolved publication correction: "+r.id);
  if(!/^Q\d+-\d+$/.test(r.id)||Object.hasOwn(entries,r.id))throw Error("Invalid event ID: "+r.id);
  const sources=[];
  for(const e of r.evidence.filter(e=>e.access==="direct")){
   if(!/^https:\/\/[a-z0-9.-]+(?::443)?(?:[/?#]|$)/i.test(e.url)||!e.locator?.trim())throw Error("Invalid public evidence: "+r.id);
   if(!indices.has(e.url)){indices.set(e.url,urls.length);urls.push(e.url);}
   sources.push([indices.get(e.url),e.locator]);
  }
  if(!sources.length)throw Error("No direct public evidence: "+r.id);
  entries[r.id]={...(r.editorialNote?{note:r.editorialNote}:{}),sources};
 }
 return "// Generated by scripts/build-author-history-public-v1.mjs; do not edit.\nexport const publicHistoryEvidence = "+JSON.stringify({urls,entries})+";\n";
}

if(process.argv[1] && pathToFileURL(resolve(process.argv[1])).href===import.meta.url){
 const ledger=JSON.parse(readFileSync(new URL("../docs/data/author-history-evidence-ledger-v1.json",import.meta.url),"utf8"));
 writeFileSync(new URL("../src/core/author-history-public-v1.js",import.meta.url),renderPublicHistory(ledger),"utf8");
}
